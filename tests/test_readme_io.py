import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from readme_io import format_readme, parse_readme


class ReadmeFormatTest(unittest.TestCase):
    def test_written_file_reads_back_the_same(self):
        fields = [
            ("Experiment name", "Drug screen: plate 2"),
            ("Storage Location", ""),
            ("Notes", "First line\n\n# not a heading\nconcentration: 10 uM"),
        ]
        filename_key = [("ctrl", "Vehicle control"), ("B", "10 uM Drug Y")]
        metadata = {"System Name": "LSM 980", "Channel Names": ["DAPI", "GFP"], "Size Z": "12"}

        text = format_readme("# Generated by ReMInD", fields, filename_key, metadata)
        read_fields, read_key, read_metadata = parse_readme(text)

        # Empty single-line fields are not returned, which is what lets a
        # loaded file leave those form fields as they were.
        self.assertEqual(read_fields, {label: value for label, value in fields if value})
        self.assertEqual(read_key, filename_key)
        self.assertEqual(read_metadata, metadata)

    def test_reads_file_written_by_version_3_0_0(self):
        # ReadMe files are kept alongside data for years, so files written by
        # earlier releases must keep loading. This is v3.0.0 output verbatim.
        text = (
            "# Generated by ReMInD v3.0.0 — Nicholas Condon, IMB Microscopy: UQ, June 2026\n"
            "\n"
            "Experiment name: EXP5\n"
            "Storage Location: \n"
            "Immersion: Other\n"
            "Immersion (Other): Immersol 518F\n"
            "Notes:\n"
            "---\n"
            "[2025-03-18 11:24:16] started\n"
            "---\n"
            "\n"
            "# Filename Key\n"
            "ctrl: Vehicle control\n"
            "\n"
            "# Extracted Image Metadata\n"
            "System Name: LSM 880\n"
            "Channel Names: Ch1, T PMT\n"
            "Size Z: 1\n"
        )
        fields, filename_key, metadata = parse_readme(text)

        self.assertEqual(fields, {
            "Experiment name": "EXP5",
            "Immersion": "Other",
            "Immersion (Other)": "Immersol 518F",
            "Notes": "[2025-03-18 11:24:16] started",
        })
        self.assertEqual(filename_key, [("ctrl", "Vehicle control")])
        self.assertEqual(metadata, {
            "System Name": "LSM 880",
            "Channel Names": ["Ch1", "T PMT"],
            "Size Z": "1",
        })


if __name__ == "__main__":
    unittest.main()
