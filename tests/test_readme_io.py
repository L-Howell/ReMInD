import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from readme_io import format_json, format_readme, parse_json, parse_readme


FIELDS = [
    ("Experiment name", "Drug screen: plate 2"),
    ("Storage Location", ""),
    # Free text can hold anything, including the line that closes the block.
    ("Notes", "First line\n\n# not a heading\n---\nconcentration: 10 uM"),
]
FILENAME_KEY = [("ctrl", "Vehicle control"), ("t: 24h", "24 hours -> fixed")]
METADATA = {"System Name": "LSM 980", "Channel Names": ["DAPI", "GFP"], "Size Z": "12"}
# Empty single-line fields are not returned, which is what lets a loaded file
# leave those form fields as they were.
FIELDS_READ_BACK = {label: value for label, value in FIELDS if value}


class ReadmeFormatTest(unittest.TestCase):
    def test_written_readme_reads_back_the_same(self):
        text = format_readme("# Generated by ReMInD", FIELDS, FILENAME_KEY, METADATA)
        self.assertEqual(parse_readme(text), (FIELDS_READ_BACK, FILENAME_KEY, METADATA))

    def test_written_json_reads_back_the_same(self):
        text = format_json(FIELDS, FILENAME_KEY, METADATA)
        self.assertEqual(parse_json(text), (FIELDS_READ_BACK, FILENAME_KEY, METADATA))


if __name__ == "__main__":
    unittest.main()
